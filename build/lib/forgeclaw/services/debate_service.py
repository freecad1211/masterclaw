from datetime import datetime, timezone
from pathlib import Path

from forgeclaw.agents.demo_agents import DemoArchitect, DemoCritic, DemoJudge
from forgeclaw.core.settings import settings
from forgeclaw.models.debate import AgentMessage, DebateRecord, DebateRequest
from forgeclaw.models.openai_compatible import OpenAICompatibleClient

_PROMPT_ROOT = Path(__file__).resolve().parents[2] / "prompts"


def _read_prompt(name: str) -> str:
    path = _PROMPT_ROOT / name
    try:
        return path.read_text(encoding="utf-8")
    except OSError as exc:
        raise RuntimeError(f"Required ForgeClaw prompt is missing: {path.name}") from exc


class DebateService:
    def __init__(self, database_path: str | None = None) -> None:
        self.database_path = database_path or settings.database_path
        self.architect = DemoArchitect()
        self.critic = DemoCritic()
        self.judge = DemoJudge()
        self.model_client = OpenAICompatibleClient()
        self.core_prompt = _read_prompt("system.md")

    def _complete(self, role: str, task: str) -> str:
        role_prompt = _read_prompt(f"roles/{role}.md")
        return self.model_client.complete(
            system_prompt=f"{self.core_prompt}\n\n--- Assigned role ---\n{role_prompt}",
            user_prompt=task,
        )

    @staticmethod
    def _request_context(request: DebateRequest) -> str:
        return f"Goal/topic:\n{request.topic}\n\nUser context:\n{request.context or '(none supplied)'}"

    def _run_live(self, request: DebateRequest) -> list[AgentMessage]:
        context = self._request_context(request)
        proposal = AgentMessage(
            role="architect",
            stage="proposal",
            content=self._complete(
                "architect",
                f"{context}\n\nCreate an initial proposal. Include assumptions, trade-offs, risks, and verifiable acceptance criteria.",
            ),
            evidence=[f"Generated by configured OpenAI-compatible model: {self.model_client.model}. No external sources were independently verified."],
        )
        messages = [proposal]

        for round_index in range(request.max_rounds):
            critique = AgentMessage(
                role="critic",
                stage="critique",
                content=self._complete(
                    "critic",
                    f"{context}\n\nDebate round: {round_index + 1}/{request.max_rounds}\n\nCurrent proposal:\n{proposal.content}\n\nIdentify prioritized issues and concrete mitigations.",
                ),
                evidence=["Model-generated review; not an independent verification of factual claims."],
            )
            messages.append(critique)

            if round_index < request.max_rounds - 1:
                proposal = AgentMessage(
                    role="architect",
                    stage="revision",
                    content=self._complete(
                        "architect",
                        f"{context}\n\nRevise the proposal in response to the critique. Explicitly address each high-severity issue; retain justified disagreements.\n\nCurrent proposal:\n{proposal.content}\n\nCritique:\n{critique.content}",
                    ),
                    evidence=[f"Revision generated by configured model: {self.model_client.model}."],
                )
                messages.append(proposal)

        decision = AgentMessage(
            role="judge",
            stage="decision",
            content=self._complete(
                "judge",
                f"{context}\n\nDebate transcript:\n"
                + "\n\n".join(f"[{item.role} / {item.stage}]\n{item.content}" for item in messages)
                + "\n\nMake a decision based on requirements, evidence, risks, and verification—not vote count.",
            ),
            evidence=["Model-generated synthesis; verify cited claims and run listed tests before relying on the decision."],
        )
        messages.append(decision)
        return messages

    def _run_demo(self, request: DebateRequest) -> list[AgentMessage]:
        proposal = self.architect.propose(request)
        messages = [proposal]
        for round_index in range(request.max_rounds):
            critique = self.critic.critique(request, proposal)
            if round_index:
                critique.content = f"Round {round_index + 1} follow-up: {critique.content}"
            messages.append(critique)
            if round_index < request.max_rounds - 1:
                proposal = AgentMessage(
                    role="architect",
                    stage="revision",
                    content=(
                        f"Revision after round {round_index + 1}: retain the minimal design, "
                        "make the provider boundary explicit, and require verification before side effects."
                    ),
                    evidence=["Deterministic demo fixture; not model-generated evidence."],
                )
                messages.append(proposal)
        decision = self.judge.decide(request, messages[0], messages[1])
        messages.append(decision)
        return messages

    def run(self, request: DebateRequest) -> DebateRecord:
        messages = self._run_live(request) if self.model_client.is_configured else self._run_demo(request)
        decision = messages[-1].content
        return DebateRecord(
            topic=request.topic,
            context=request.context,
            messages=messages,
            decision=decision,
            unresolved_questions=[
                "Verify any model-generated factual claims against independent sources.",
                "Choose secure Obsidian connectivity: private network, authenticated tunnel, or server-side Vault sync.",
            ],
            created_at=datetime.now(timezone.utc),
        )
